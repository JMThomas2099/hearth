export function groceryByAisle(items: GroceryItem[] = WEEK_GROCERY) {
  return AISLES.map((aisle) => ({
    aisle,
    items: items.filter((i) => i.aisle === aisle),
  })).filter((g) => g.items.length > 0);
}

