export function allMeals(): Meal[] {
  return WEEK.flatMap((day) => Object.values(day.meals));
}

export function dayTotals(day: DayPlan) {
  const meals = Object.values(day.meals);
  return meals.reduce(
    (acc, m) => ({
      calories: acc.calories + m.calories,
      protein: acc.protein + m.protein,
      carbs: acc.carbs + m.carbs,
      fat: acc.fat + m.fat,
      minutes: acc.minutes + (m.heat === "Reheat" || m.heat === "Assemble" ? m.minutes : m.minutes),
    }),
    { calories: 0, protein: 0, carbs: 0, fat: 0, minutes: 0 },
  );
}

export function weekAverages() {
  const totals = WEEK.map(dayTotals);
  const n = totals.length;
  return {
    calories: Math.round(totals.reduce((s, t) => s + t.calories, 0) / n),
    protein: Math.round(totals.reduce((s, t) => s + t.protein, 0) / n),
    carbs: Math.round(totals.reduce((s, t) => s + t.carbs, 0) / n),
    fat: Math.round(totals.reduce((s, t) => s + t.fat, 0) / n),
  };
}

