export function upcomingHolidays(from = new Date()) {
  const t = from.getTime();
  const upcoming = HOLIDAYS.filter((h) => new Date(h.iso + "T12:00:00").getTime() >= t).sort(
    (a, b) => +new Date(a.iso) - +new Date(b.iso),
  );
  const past = HOLIDAYS.filter((h) => new Date(h.iso + "T12:00:00").getTime() < t).sort(
    (a, b) => +new Date(a.iso) - +new Date(b.iso),
  );
  return { upcoming, past };
}
